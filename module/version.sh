function module::Version() {
    local name="Chprompt"
    local version="v0.1.20261007"
    local developer="Senzdetta"
    local homepage="https://github.com/Senzdetta/Chprompt"

    echo -e "${color_DG}- ${color_GG}${name} ${color_DG}-${color_N}"
    echo -e "${color_N}Version: ${color_GG}${version}${color_N}"
    echo -e "${color_N}Developer: ${color_GG}${developer}${color_N}"
    echo -e "${color_N}Homepage: ${color_GG}${homepage}${color_N}"

    return 0
}

